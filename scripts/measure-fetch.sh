#!/bin/sh
# What does the app actually ask GitHub for, and how long does each answer take?
#
# `measure-startup.sh` answers "how long until the screen is worth looking at".
# This one answers the question behind it: *which* calls make up that time. It
# runs the real binary with a `gh` in front that **never answers on its own** —
# it logs argv and duration, then execs the real `gh`. The measurements stay
# real; only the bookkeeping is added.
#
# Usage:  sh scripts/measure-fetch.sh [seconds_to_watch] [binary]
#         default: 20 seconds, target/debug/gtasks
#
# Why a generated wrapper instead of a committed file named `gh`: a file called
# `gh` in a repository is an attractive nuisance — one stray `PATH=$PWD/...`
# later and every gh call in the project is silently routed through it. The
# wrapper is written into a private temp directory (0700), embeds the **absolute
# path of the real gh resolved before any PATH change**, and is removed on exit.
#
# Two traps this script already knows about, both measured:
#
#   * `PATH=x tmux new-session ...` does NOT reach the session when a tmux
#     server is already running (tmux special-cases PATH; the session inherits
#     the server's). `env PATH=... ` inside the command string is what works.
#   * the app resolves `gh` once at startup and refuses a program it cannot
#     verify (S2), so the wrapper must be a regular executable owned by us with
#     no group/world write bits — hence 0700 and a temp dir of our own.
set -eu

seconds=${1:-20}
bin=${2:-target/debug/gtasks}
session="gtasks-fetch-$$"
payload=$(mktemp -d)
trap 'tmux kill-session -t "$session" 2>/dev/null || true; rm -rf "$payload"' EXIT INT TERM

cd "$(git rev-parse --show-toplevel)"

if [ ! -x "$bin" ]; then
    echo "no binary at $bin — build it first" >&2
    exit 2
fi
abs_bin=$(cd "$(dirname "$bin")" && pwd)/$(basename "$bin")

real_gh=$(command -v gh || true)
if [ -z "$real_gh" ]; then
    echo "no gh on PATH — nothing to wrap" >&2
    exit 2
fi

log="$payload/calls.log"
: > "$log"
mkdir -p "$payload/bin"
wrapper="$payload/bin/gh"
cat > "$wrapper" <<EOF
#!/bin/sh
# Generated by scripts/measure-fetch.sh: log, then delegate. Never answers itself.
start=\$(date +%s%N)
printf 'START %s %s\\n' "\$start" "\$*" >> "$log"
"$real_gh" "\$@"
rc=\$?
end=\$(date +%s%N)
printf 'END %s rc=%s dur=%s %s\\n' "\$end" "\$rc" "\$(( (end - start) / 1000000 ))" "\$*" >> "$log"
exit \$rc
EOF
chmod 0700 "$wrapper"

echo "source sha        : $(git rev-parse --short HEAD)"
echo "binary            : $abs_bin"
echo "binary sha256     : $(sha256sum "$abs_bin" | cut -c1-16)"
echo "real gh           : $real_gh"
echo "watching          : ${seconds}s"
echo

# `env` inside the command string, not `-e`: see the note at the top.
tmux new-session -d -s "$session" -x 120 -y 30 \
    "env PATH=$payload/bin:\$PATH $abs_bin"

sleep "$seconds"
tmux kill-session -t "$session" 2>/dev/null || true

if [ ! -s "$log" ]; then
    echo "no gh calls were logged — the wrapper was not used, so this run measured nothing"
    exit 3
fi

awk '
    /^END / {
        # END <ns> rc=<n> dur=<ms> <argv...>
        rc = $3; dur = $4;
        sub(/^[^ ]+ [^ ]+ [^ ]+ [^ ]+ /, "");
        printf "  %7d ms  rc=%-3s %s\n", substr(dur, 5), substr(rc, 4), substr($0, 1, 96);
        total += substr(dur, 5); n += 1;
        if (substr(dur, 5) + 0 > worst + 0) worst = substr(dur, 5);
    }
    END {
        printf "\n  calls: %d · sum: %d ms · slowest: %d ms\n", n, total, worst;
        printf "  wall clock is the question: sum is what serialising would cost, slowest is the floor.\n";
    }
' "$log"
